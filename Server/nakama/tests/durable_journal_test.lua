package.path = "Server/nakama/?.lua;Server/nakama/modules/?.lua;Server/nakama/tests/?.lua;" .. package.path
local Fixture = require("storage_fault_fixture")
local passed = 0
local function test(name, fn)
  local f = Fixture.new(); f.install(); f.seed("a")
  local module = require("duel_match3_journal")
  local j = require("tests.journal_fixture_admission").wrap(module.new({ stats_collection = "stats", stats_key = "summary" }),f)
  local ok, err = pcall(fn, f, j, module)
  assert(ok, name .. ": " .. tostring(err)); passed = passed + 1; print("PASS " .. name)
end
local function reward_builder(f, amount)
  return function(plan)
    local progress, version = f.read_progress("a")
    progress.gold = progress.gold + (amount or plan.gold)
    return { f.build_progress("a", progress, version) }, { reward_gold = amount or plan.gold }
  end
end
local PLAN = { gold = 25, achievement_deltas = { wins = 1 }, match_stats = { mode = "mine", won = true } }
test("intent persists before any wallet writes and conflicting reroll is rejected", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN)); assert(f.read_progress("a").gold == 100)
  local ok, err = j.prepare("a", "r", "pve", { gold = 999 }); assert(not ok and err == "result_plan_conflict")
end)
test("wallet receipt and journal marker commit in one atomic batch", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN)); assert(j.commit("a", "r", reward_builder(f)))
  assert(f.read_progress("a").gold == 125 and j.read("a", "r").status == "committed")
  local batch = f.writes[#f.writes]; assert(#batch == 4)
  assert(batch[4].key=="retention_v2", "ticket state must share the wallet/journal CAS batch")
  assert(j.commit("a", "r", function() error("duplicate builder must not execute") end))
  assert(f.read_progress("a").gold == 125)
end)
test("precommit storage fault cannot grant wallet or mark reward complete", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN)); f.fail_before = true
  assert(not j.commit("a", "r", reward_builder(f)))
  assert(f.read_progress("a").gold == 100 and j.read("a", "r").status == "prepared")
end)
test("lost acknowledgement after commit survives new process without another grant", function(f, j, module)
  assert(j.prepare("a", "r", "pve", PLAN)); f.fail_after = true
  assert(not j.commit("a", "r", reward_builder(f))); assert(f.read_progress("a").gold == 125)
  j = require("tests.journal_fixture_admission").wrap(module.new({ stats_collection = "stats", stats_key = "summary" }),f)
  assert(j.recover("a", { pve = function() error("committed reward cannot replay") end }))
  assert(f.read_progress("a").gold == 125 and j.read("a", "r").status == "complete")
  assert(f.get("stats", "a", "summary").achievement_stats.wins == 1)
end)
test("process loss after intent replays frozen reward plan", function(f, j, module)
  assert(j.prepare("a", "r", "pve", PLAN)); j = require("tests.journal_fixture_admission").wrap(module.new({ stats_collection = "stats", stats_key = "summary" }),f)
  assert(j.recover("a", { pve = function(uid, id, plan) return reward_builder(f)(plan) end }))
  assert(f.read_progress("a").gold == 125 and j.read("a", "r").status == "complete")
end)
test("achievement DB failure never replays a committed wallet", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN)); assert(j.commit("a", "r", reward_builder(f)))
  f.fail_before = true; assert(not j.deliver_effects("a", "r"))
  assert(f.read_progress("a").gold == 125 and j.read("a", "r").status == "committed")
  f.fail_before = false; assert(j.deliver_effects("a", "r")); assert(j.deliver_effects("a", "r"))
  local summary = f.get("stats", "a", "summary")
  assert(summary.achievement_stats.wins == 1 and summary.played == 1 and summary.modes.mine.wins == 1)
end)
test("outbox increment and delivered receipt survive postcommit process fault", function(f, j)
  assert(j.prepare("a", "r", "effects", { achievement_deltas = { cross = 4 } })); f.fail_after = true
  assert(not j.deliver_effects("a", "r")); assert(j.deliver_effects("a", "r"))
  assert(f.get("stats", "a", "summary").achievement_stats.cross == 4)
end)
test("concurrent effects workers cannot increment twice", function(f, j)
  assert(j.prepare("a", "r", "effects", { achievement_deltas = { cross = 2 } }))
  f.before_write = function() assert(j.deliver_effects("a", "r")) end
  assert(j.deliver_effects("a", "r")); assert(f.get("stats", "a", "summary").achievement_stats.cross == 2)
end)
test("wallet CAS retry preserves another purchase", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN))
  f.before_write = function() local p = f.read_progress("a"); p.gold = p.gold - 40; f.put("progress", "a", "profile", p) end
  assert(j.commit("a", "r", reward_builder(f))); assert(f.read_progress("a").gold == 85)
end)
test("unknown handler remains durable and permission-private", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN)); assert(not j.recover("a", {}))
  assert(j.read("a", "r").status == "prepared")
  for _, batch in ipairs(f.writes) do for _, op in ipairs(batch) do if op.collection == "duel_match3_journal" then assert(op.permission_read == 0 and op.permission_write == 0) end end end
end)
test("refund abort marker and reward intent are mutually exclusive", function(f, j)
  local writes = assert(j.abort_writes("a", "r", "orphan")); f.nk.storage_write(writes)
  assert(not j.prepare("a", "r", "pve", PLAN))
  assert(j.prepare("a", "s", "pve", PLAN)); local abort, err = j.abort_writes("a", "s", "orphan")
  assert(not abort and err == "result_pending")
end)
test("bad builders cannot bypass version or owner boundaries", function(f, j)
  assert(j.prepare("a", "r", "pve", PLAN))
  local ok, err = j.commit("a", "r", function() return {{ collection = "progress", user_id = "b", version = "*" }}, {} end)
  assert(not ok and err == "cross_user_reward_builder" and f.read_progress("a").gold == 100)
end)
print("durable_journal_test: " .. passed .. " passed")
